 const bounds=await page.$eval("#game-menu .journal-body",e=>{const b=e.getBoundingClientRect();return {x:b.x+b.width/2,y:b.y+b.height/2,max:e.scrollHeight-e.clientHeight}});
 await page.mouse.move(bounds.x,bounds.y);await page.mouse.wheel({deltaY:500});await wait(200);
 check("Guide native wheel scrolling",await page.$eval("#game-menu .journal-body",e=>e.scrollTop>0),bounds);
 await page.$eval("#game-menu .journal-body",e=>e.scrollTop=0);
 await page.click('[data-tab="planets"]');
 check("Atlas has six destination buttons",await page.$$eval("#planet-bar [data-planet]",e=>e.length===6));
 await page.screenshot({path:new URL("desktop-atlas.png",out).pathname.replace(/^\/(C:)/,"$1")});
 await page.focus('[data-action="close-menu"]');await page.keyboard.down("Shift");await page.keyboard.press("Tab");await page.keyboard.up("Shift");
 check("Guide traps reverse Tab",await page.evaluate(()=>document.getElementById("game-menu").contains(document.activeElement)&&document.activeElement.dataset.action!=="close-menu"));
 await page.keyboard.press("Escape");
 check("Escape returns focus to guide opener",await page.evaluate(()=>!__game.hud.isMenuOpen()&&document.activeElement.dataset.action==="guide"));
 await page.evaluate(()=>{__game.player.health=100;__game.player.hunger=100;__game.player.suitShield=100;__game.loop.inventory.wood=20;__game.loop.inventory.stone=10;});
 await page.click('[data-action="satchel"]');
 await page.waitForFunction(()=>!document.querySelector('[data-recipe="plane_frame"]').disabled);
 await page.focus('[data-recipe="plane_frame"]');await page.keyboard.press("Enter");
 check("Native Enter crafts skiff",await page.evaluate(()=>__game.loop.planeCrafted&&__game.loop.inventory.wood===8));
 await page.click('[data-craft-tab="camp"]');
 await page.screenshot({path:new URL("desktop-camp.png",out).pathname.replace(/^\/(C:)/,"$1")});
 const structuresBefore=await page.evaluate(()=>__game.structureStore.byId.size);
 await page.click('[data-structure="campfire"]');await wait(200);
 check("Selecting camp plan only previews",await page.evaluate((n)=>__game.structureStore.byId.size===n&&!document.body.classList.contains("crafting-open"),structuresBefore));
 await page.waitForSelector("#build-strip.show",{visible:true});
 await page.focus("#build-strip");await page.keyboard.press("Enter");await wait(150);
 check("Native placement prompt commits selected plan",await page.evaluate(n=>__game.structureStore.byId.size===n+1,structuresBefore));
 await page.setViewport({width:390,height:844,deviceScaleFactor:1,isMobile:true,hasTouch:true}); await page.waitForFunction(()=>window.__game && !document.getElementById("splash"),{timeout:120000});
 await page.evaluate(()=>{document.body.classList.add("touch");__game.controls.touch.enable();});
 await page.click('[data-action="guide"]');
 await page.screenshot({path:new URL("mobile-atlas.png",out).pathname.replace(/^\/(C:)/,"$1")});
 const portrait=await page.$eval("#game-menu .journal-card",e=>{const r=e.getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom,width:innerWidth,height:innerHeight}});
 check("Portrait journal fits viewport",portrait.x>=0&&portrait.y>=0&&portrait.right<=portrait.width&&portrait.bottom<=portrait.height,portrait);
 await page.click('[data-action="close-menu"]');
 await page.screenshot({path:new URL("mobile-world.png",out).pathname.replace(/^\/(C:)/,"$1")});
