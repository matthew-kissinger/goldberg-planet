 check("Touch satchel button opens panel",await page.evaluate(()=>document.body.classList.contains("crafting-open")));
 await page.click('[data-craft-tab="make"]');
 await page.screenshot({path:new URL("mobile-satchel.png",out).pathname.replace(/^\/(C:)/,"$1")});
